# Lambda Function
# ===============
# Sum of 2 numbers
# ----------------
lambda a,b:a+b

# Product of 3 numbers
# --------------------
lambda a,b,c:a*b*c

# Cube of a number
# ----------------
lambda x:x*x*x

# First letter of a string
# ------------------------
lambda s: s[0]

# Length of a string
# ------------------
lambda s: len(s)

# Reverse of a string
# -------------------
lambda s: s[::-1]

# Name value from a dictionary
# ----------------------------
lambda d: d['name']

# Second element from a list
# --------------------------
lambda l: l[1]

# Add 10 to a number
# ------------------
lambda x: x + 10